def prerequisite(key):
    if key not in sources:
        return '基础项目，无上一级要求', '无'
    source = items[sources[key]]
    evolution = next(e for e in source['evolutions'] if e['targetKey'] == key)
    extra = '；'.join(c['expression'] for c in evolution['conditions']) or '无'
    if extra != '无':
        extra = re.sub(r' >= 1\b', '', extra)
        extra = '持有「' + extra + '」'
    return f"{source['displayName']} {evolution['level']} 级", extra


def effects(key, mode):
    item = items[key]
    values = []
    for relation in item[mode]:
        data = []
        for name in relation['converts']:
            convert = curves[name]
            assert convert['source'] == item['asset']
            assert convert['curve'][-1]['time'] == 1
            data.append(convert['curve'][-1]['value'])

        def replace(match):
            value = data[int(match[1])]
            return f'{value * 100:.0f}%' if match[2] == 'P0' else f'{value:.4f}'.rstrip('0').rstrip('.')

        values.append(re.sub(r'\{(\d+):(N0|P0)\}', replace, relation['description']))
    return '；'.join(re.sub(r' {2,}', '；', value) for value in values) or '未配置'


def table(headers, rows):
    return '\n'.join(['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |'] +
                     ['| ' + ' | '.join(map(str, row)) + ' |' for row in rows])


